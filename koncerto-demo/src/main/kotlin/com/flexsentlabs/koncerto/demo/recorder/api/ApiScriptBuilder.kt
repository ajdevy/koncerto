package com.flexsentlabs.koncerto.demo.recorder.api

/**
 * Renders a parsed [ApiScenario] into the bash script the recorder runs inside a visible terminal.
 *
 * The script issues real curl calls against the deployed target and shows each one being typed and
 * answered, so the resulting video records the API actually being exercised rather than replaying a
 * transcript captured elsewhere. Each request is executed as a bash array — never `eval` — so a
 * scenario value can't be re-parsed into extra shell words, and each request appends a
 * machine-readable record to a JSONL file the recorder reads back to decide pass/fail.
 *
 * Pure string building with no I/O, so the exact emitted script is unit-testable.
 */
object ApiScriptBuilder {

    /** Placeholders of the form `{{name}}` resolve to values captured by an earlier `save`. */
    private val PLACEHOLDER = Regex("""\{\{\s*([A-Za-z_][A-Za-z0-9_]*)\s*}}""")

    private const val MAX_WAIT_MS = 10_000

    fun build(
        scenario: ApiScenario,
        resultPath: String,
        issueIdentifier: String = "",
        typingDelaySeconds: String = "0.012"
    ): String {
        val body = scenario.steps
            .mapIndexed { index, step -> renderStep(step, index + 1) }
            .joinToString("\n\n")
        return listOf(
            preamble(resultPath, typingDelaySeconds),
            banner(scenario, issueIdentifier),
            body,
            epilogue()
        ).joinToString("\n\n") + "\n"
    }

    private fun preamble(resultPath: String, typingDelaySeconds: String): String = """
#!/bin/bash
# Generated by Koncerto ApiScriptBuilder — executes the ticket's API demo scenario.
# Deliberately not `set -e`: a failing assertion must still be shown on screen and recorded,
# not abort the run half-way through the demo.
set -u

TARGET_URL="${'$'}{TARGET_URL%/}"
RESULT_FILE=${shellQuote(resultPath)}
TYPING_DELAY=${shellQuote(typingDelaySeconds)}
FAILURES=0
: > "${'$'}RESULT_FILE"

BOLD=${'$'}'\e[1m'; DIM=${'$'}'\e[2m'; RED=${'$'}'\e[31m'; GREEN=${'$'}'\e[32m'
CYAN=${'$'}'\e[36m'; YELLOW=${'$'}'\e[33m'; RESET=${'$'}'\e[0m'

cat > /tmp/jsonpath.py <<'PYEOF'
import json, sys
path, source = sys.argv[1], sys.argv[2]
try:
    data = json.load(open(source))
except Exception:
    sys.exit(1)
for part in [p for p in path.split('.') if p]:
    if isinstance(data, list):
        try:
            data = data[int(part)]
        except Exception:
            sys.exit(1)
    elif isinstance(data, dict) and part in data:
        data = data[part]
    else:
        sys.exit(1)
print(data if not isinstance(data, (dict, list)) else json.dumps(data))
PYEOF

cat > /tmp/pretty.py <<'PYEOF'
import json, sys
raw = sys.stdin.read()
try:
    print(json.dumps(json.loads(raw), indent=2, ensure_ascii=False))
except Exception:
    sys.stdout.write(raw)
PYEOF

cat > /tmp/record.py <<'PYEOF'
import json, sys
step, method, path, code, expected, ok, error, dest = sys.argv[1:9]
with open(dest, 'a') as fh:
    fh.write(json.dumps({
        "step": int(step), "method": method, "path": path,
        "code": code, "expected": expected,
        "ok": ok == "1", "error": error,
    }) + "\n")
PYEOF

# Types text out one character at a time so the video shows the command being written, the way a
# person demonstrating an API would.
type_out() {
  local text="${'$'}1" i
  for (( i=0; i<${'$'}{#text}; i++ )); do
    printf '%s' "${'$'}{text:${'$'}i:1}"
    sleep "${'$'}TYPING_DELAY"
  done
  printf '\n'
}

# Re-quotes any argument that isn't a bare word, so the command on screen is one a viewer could
# copy and paste. The array is what actually runs; this only affects how it is displayed.
render_cmd() {
  local out="" arg
  for arg in "${'$'}@"; do
    case "${'$'}arg" in
      *[!A-Za-z0-9_:/.@=+-]*) out="${'$'}out '${'$'}{arg//\'/\'\\'\'}'" ;;
      *) out="${'$'}out ${'$'}arg" ;;
    esac
  done
  printf '%s' "${'$'}{out# }"
}

note() { printf '\n%s▸ %s%s\n' "${'$'}CYAN${'$'}BOLD" "${'$'}1" "${'$'}RESET"; }
pass() { printf '%s  ✓ %s%s\n' "${'$'}GREEN" "${'$'}1" "${'$'}RESET"; }
fail() { printf '%s  ✗ %s%s\n' "${'$'}RED${'$'}BOLD" "${'$'}1" "${'$'}RESET"; FAILURES=${'$'}((FAILURES+1)); }
""".trim()

    private fun banner(scenario: ApiScenario, issueIdentifier: String): String {
        val heading = listOfNotNull(
            issueIdentifier.takeIf { it.isNotBlank() },
            scenario.description.takeIf { it.isNotBlank() }
        ).joinToString(" — ").ifBlank { "API demo" }
        return """
printf '%s\n' "${'$'}{BOLD}=== ${escapeForDoubleQuotes(heading)} ===${'$'}{RESET}"
printf '%s\n' "${'$'}{DIM}target: ${'$'}TARGET_URL${'$'}{RESET}"
sleep 1
""".trim()
    }

    private fun renderStep(step: ApiStep, number: Int): String = when (step) {
        is ApiStep.Note -> "note ${shellQuote(step.note)}\nsleep 1"
        is ApiStep.Wait -> {
            val seconds = "%.2f".format(step.ms.coerceIn(0, MAX_WAIT_MS) / 1000.0)
            val note = if (step.note.isNotBlank()) "note ${shellQuote(step.note)}\n" else ""
            "${note}sleep $seconds"
        }
        is ApiStep.Request -> renderRequest(step, number)
    }

    private fun renderRequest(step: ApiStep.Request, number: Int): String = buildString {
        if (step.note.isNotBlank()) appendLine("note ${shellQuote(step.note)}")
        appendLine("STEP_OK=1; STEP_ERROR=\"\"")
        appendLine("CMD=(${curlCommand(step)})")
        appendLine("printf '\\n%s\$ %s' \"\${YELLOW}\" \"\${RESET}\"")
        appendLine("type_out \"\$(render_cmd \"\${CMD[@]}\")\"")
        appendLine("\"\${CMD[@]}\" > /tmp/response.txt 2>&1")
        // The status line curl prints for -i is the same text the viewer just watched scroll past,
        // so the assertion checks exactly what the video shows.
        // Anchored to a real status line: when curl cannot connect it prints `curl: (7) ...`, and an
        // unanchored parse reported "(7)" as though it were an HTTP code. 000 says "no response".
        appendLine("CODE=\$(awk 'NR==1 && \$1 ~ /^HTTP\\// {print \$2}' /tmp/response.txt)")
        appendLine("[ -z \"\$CODE\" ] && CODE=\"000\"")
        appendLine("sed -n '1,/^\\r*\$/p' /tmp/response.txt | head -12")
        appendLine("sed '1,/^\\r*\$/d' /tmp/response.txt > /tmp/body.txt")
        appendLine("python3 /tmp/pretty.py < /tmp/body.txt | head -40")
        step.expectStatus?.let {
            appendLine("if [ \"\$CODE\" = \"$it\" ]; then")
            appendLine("  pass \"status \$CODE\"")
            appendLine("else")
            appendLine("  fail \"expected status $it but got \$CODE\"")
            appendLine("  STEP_OK=0; STEP_ERROR=\"expected $it got \$CODE\"")
            appendLine("fi")
        }
        step.expectContains?.let {
            val shown = escapeForDoubleQuotes(it.take(60))
            appendLine("if grep -qF ${shellQuote(it)} /tmp/body.txt; then")
            appendLine("  pass \"response contains $shown\"")
            appendLine("else")
            appendLine("  fail \"response does not contain $shown\"")
            appendLine("  STEP_OK=0; STEP_ERROR=\"missing $shown\"")
            appendLine("fi")
        }
        step.save.forEach { (name, path) ->
            appendLine("if SAVED_$name=\$(python3 /tmp/jsonpath.py ${shellQuote(path)} /tmp/body.txt); then")
            appendLine("  printf '%s\\n' \"\${DIM}  saved $name=\${SAVED_$name}\${RESET}\"")
            appendLine("else")
            appendLine("  SAVED_$name=\"\"")
            appendLine("  fail \"could not read ${escapeForDoubleQuotes(path)} from the response\"")
            appendLine("  STEP_OK=0; STEP_ERROR=\"save $name failed\"")
            appendLine("fi")
        }
        appendLine(
            "python3 /tmp/record.py $number ${shellQuote(step.method)} ${shellQuote(step.path)} " +
                "\"\$CODE\" ${shellQuote(step.expectStatus?.toString().orEmpty())} " +
                "\"\$STEP_OK\" \"\$STEP_ERROR\" \"\$RESULT_FILE\""
        )
        append("sleep 2")
    }

    private fun epilogue(): String = """
printf '\n%s\n' "${'$'}{BOLD}=== demo complete: ${'$'}FAILURES failed assertion(s) ===${'$'}{RESET}"
sleep 3
exit 0
""".trim()

    /**
     * The curl argument vector for [step], rendered as the inside of a bash array literal.
     *
     * `-i` (rather than `-w`/`-D`) keeps it to one readable command whose own output carries the
     * status line the script parses, so what the viewer reads and what the assertion checks are the
     * same bytes. Every element is separately quoted, so a value carrying a space or a shell
     * metacharacter stays a single argument.
     */
    internal fun curlCommand(step: ApiStep.Request): String = buildString {
        append("curl -sS -i -X ")
        append(doubleQuoted(step.method))
        append(' ')
        val path = step.path.let { if (it.startsWith("/")) it else "/$it" }
        append("\"\$TARGET_URL${interpolate(path)}\"")
        step.headers.forEach { (name, value) ->
            append(" -H \"")
            append(escapeForDoubleQuotes(name))
            append(": ")
            append(interpolate(value))
            append('"')
        }
        step.body?.let {
            append(" --data-raw ")
            append(doubleQuoted(it))
        }
    }

    private fun doubleQuoted(text: String): String = "\"${interpolate(text)}\""

    /**
     * Renders [text] for the inside of a bash double-quoted string, turning `{{name}}` placeholders
     * into references to the shell variable a prior `save` populated. Literal segments are escaped
     * so nothing else in the scenario can expand — a body containing `$HOME` or a backtick stays
     * literal instead of executing.
     */
    internal fun interpolate(text: String): String = buildString {
        var cursor = 0
        PLACEHOLDER.findAll(text).forEach { match ->
            append(escapeForDoubleQuotes(text.substring(cursor, match.range.first)))
            append("\${SAVED_${match.groupValues[1]}}")
            cursor = match.range.last + 1
        }
        append(escapeForDoubleQuotes(text.substring(cursor)))
    }

    /** Escapes the four characters bash still interprets inside double quotes. */
    internal fun escapeForDoubleQuotes(text: String): String =
        text.replace("\\", "\\\\")
            .replace("\"", "\\\"")
            .replace("$", "\\$")
            .replace("`", "\\`")

    /** Wraps [text] in single quotes, which bash treats as fully literal. */
    internal fun shellQuote(text: String): String = "'" + text.replace("'", "'\\''") + "'"
}
